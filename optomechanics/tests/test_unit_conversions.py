"""Unit tests for data_analysis/unit_conversions.py."""
import numpy as np
from numpy.testing import assert_allclose
from optomechanics.data_analysis.unit_conversions import watts_ratio_to_dB, dB_to_watts_ratio, dB_to_linear_voltage, linear_voltage_to_dB, Vpp_to_Vrms, Vp_to_Vrms, Vrms_to_Vpp, Vrms_to_Vp, Vrms_to_watts, watts_to_dBw, RMS_to_dBw, RMS_to_dBm, dBw_to_watts, dBm_to_dBw, dBm_to_RMS, watts_to_dBm, dBm_to_watts, Vrms_squared_to_watts

def test_watts_ratio_unity(): assert_allclose(watts_ratio_to_dB(1.0), 0.0, atol=1e-12)
def test_watts_ratio_ten(): assert_allclose(watts_ratio_to_dB(10.0), 10.0, atol=1e-12)
def test_watts_ratio_hundred(): assert_allclose(watts_ratio_to_dB(100.0), 20.0, atol=1e-12)
def test_watts_ratio_tenth(): assert_allclose(watts_ratio_to_dB(0.1), -10.0, atol=1e-12)
def test_dB_to_watts_zero(): assert_allclose(dB_to_watts_ratio(0.0), 1.0, atol=1e-12)
def test_dB_to_watts_ten(): assert_allclose(dB_to_watts_ratio(10.0), 10.0, atol=1e-10)
def test_dB_to_watts_neg_ten(): assert_allclose(dB_to_watts_ratio(-10.0), 0.1, atol=1e-12)
def test_dB_to_watts_roundtrip(): assert_allclose(dB_to_watts_ratio(watts_ratio_to_dB(5.0)), 5.0, rtol=1e-12)
def test_dB_to_linear_voltage_zero(): assert_allclose(dB_to_linear_voltage(0.0), 1.0, atol=1e-12)
def test_dB_to_linear_voltage_20(): assert_allclose(dB_to_linear_voltage(20.0), 10.0, atol=1e-10)
def test_dB_to_linear_voltage_neg20(): assert_allclose(dB_to_linear_voltage(-20.0), 0.1, atol=1e-12)
def test_linear_voltage_to_dB_unity(): assert_allclose(linear_voltage_to_dB(1.0), 0.0, atol=1e-12)
def test_linear_voltage_to_dB_ten(): assert_allclose(linear_voltage_to_dB(10.0), 20.0, atol=1e-10)
def test_linear_voltage_roundtrip(): assert_allclose(dB_to_linear_voltage(linear_voltage_to_dB(3.5)), 3.5, rtol=1e-12)
def test_Vpp_to_Vrms(): assert_allclose(Vpp_to_Vrms(2.0), 2.0/(2*np.sqrt(2)), rtol=1e-12)
def test_Vp_to_Vrms(): assert_allclose(Vp_to_Vrms(1.0), 1.0/np.sqrt(2), rtol=1e-12)
def test_Vrms_to_Vpp(): assert_allclose(Vrms_to_Vpp(1.0), 2*np.sqrt(2), rtol=1e-12)
def test_Vrms_to_Vp(): assert_allclose(Vrms_to_Vp(1.0), np.sqrt(2), rtol=1e-12)
def test_Vpp_Vrms_roundtrip(): assert_allclose(Vrms_to_Vpp(Vpp_to_Vrms(4.0)), 4.0, rtol=1e-12)
def test_Vp_Vrms_roundtrip(): assert_allclose(Vrms_to_Vp(Vp_to_Vrms(3.0)), 3.0, rtol=1e-12)
def test_Vrms_to_watts_50(): assert_allclose(Vrms_to_watts(1.0, 50), 0.02, rtol=1e-12)
def test_Vrms_to_watts_100(): assert_allclose(Vrms_to_watts(1.0, 100), 0.01, rtol=1e-12)
def test_Vrms_to_watts_default_50(): assert_allclose(Vrms_to_watts(1.0), Vrms_to_watts(1.0, 50), rtol=1e-12)
def test_watts_to_dBw_one(): assert_allclose(watts_to_dBw(1.0), 0.0, atol=1e-12)
def test_watts_to_dBw_ten(): assert_allclose(watts_to_dBw(10.0), 10.0, atol=1e-10)
def test_watts_to_dBw_tenth(): assert_allclose(watts_to_dBw(0.1), -10.0, atol=1e-10)
def test_dBw_to_watts_zero(): assert_allclose(dBw_to_watts(0.0), 1.0, atol=1e-12)
def test_dBw_roundtrip(): assert_allclose(dBw_to_watts(watts_to_dBw(5.0)), 5.0, rtol=1e-12)
def test_dBm_to_dBw_zero(): assert_allclose(dBm_to_dBw(0.0), -30.0, atol=1e-12)
def test_dBm_to_dBw_thirty(): assert_allclose(dBm_to_dBw(30.0), 0.0, atol=1e-12)
def test_watts_to_dBm_mW(): assert_allclose(watts_to_dBm(1e-3), 0.0, atol=1e-10)
def test_watts_to_dBm_W(): assert_allclose(watts_to_dBm(1.0), 30.0, atol=1e-10)
def test_dBm_to_watts_zero_dBm(): assert_allclose(dBm_to_watts(0.0), 1e-3, rtol=1e-10)
def test_dBm_to_watts_roundtrip(): assert_allclose(dBm_to_watts(watts_to_dBm(0.005)), 0.005, rtol=1e-12)
def test_RMS_to_dBm(): assert_allclose(RMS_to_dBm(1.0, 50), 10*np.log10(0.02)+30, rtol=1e-10)
def test_RMS_to_dBw(): assert_allclose(RMS_to_dBw(1.0, 50), 10*np.log10(0.02), rtol=1e-10)
def test_dBm_to_RMS_roundtrip(): assert_allclose(dBm_to_RMS(RMS_to_dBm(0.1, 50), 50), 0.1, rtol=1e-10)
def test_Vrms_sq_to_watts_50(): assert_allclose(Vrms_squared_to_watts(1.0, 50), 0.02, rtol=1e-12)
def test_Vrms_sq_to_watts_default(): assert_allclose(Vrms_squared_to_watts(2.0), 2.0/50, rtol=1e-12)
